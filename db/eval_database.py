"""
Database models and operations for F1 Fan Evaluation System.

This module defines:
- Submission model: Stores user submissions (who submitted + their description)
- Evaluation model: Stores AI-generated scores for each submission
- EvalDatabase class: Handles all database operations (insert, query, etc.)
"""

import logging
from datetime import datetime, timezone
from typing import Any, Dict, List

import pandas as pd
from sqlalchemy import (
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    create_engine,
    event,
    inspect,
)
from sqlalchemy.engine import Engine
from sqlalchemy.orm import declarative_base, relationship, sessionmaker

# Configure logging to show INFO level messages
logging.basicConfig(level=logging.INFO)

# Create base class for SQLAlchemy models
# All our database tables will inherit from this
Base = declarative_base()


# ---------------------------
# SQLAlchemy Models
# ---------------------------
class Submission(Base):
    """
    Represents a single F1 fan submission.

    Each submission contains the user's response explaining why they're the biggest F1 fan.
    This is the input data before AI evaluation.
    """
    __tablename__ = "submissions"

    # Auto-incrementing internal database ID
    id = Column(Integer, primary_key=True, autoincrement=True)

    # Unique submission ID (from input CSV, e.g., respondent ID)
    sub_id = Column(String, unique=True, nullable=False)

    # User's email address
    email = Column(String, nullable=True)

    # The actual text describing why they're an F1 fan (this gets evaluated by AI)
    description = Column(Text, nullable=True)

    # Timestamp when this submission was ingested into the database
    processed_at = Column(DateTime(timezone=True), nullable=False)

    # How long it took to process/ingest this submission (in seconds)
    total_processing_time_in_seconds = Column(Float)

    # Relationship: One submission can have multiple evaluations
    # cascade="all, delete-orphan" means if we delete a submission, delete its evaluations too
    evaluations = relationship(
        "Evaluation", back_populates="submission", cascade="all, delete-orphan"
    )


class Evaluation(Base):
    """
    Represents AI-generated evaluation scores for a submission.

    Each evaluation contains three scores (knowledge, enthusiasm, humor) generated by AI,
    plus token usage and cost metrics for tracking API consumption.
    """
    __tablename__ = "evaluations"

    # Unique evaluation ID (generated as sub_id + random suffix)
    eval_id = Column(String, primary_key=True)

    # Foreign key linking back to the submission being evaluated
    # ondelete="CASCADE" means if the submission is deleted, this evaluation is too
    sub_id = Column(
        String, ForeignKey("submissions.sub_id", ondelete="CASCADE"), nullable=False
    )

    # F1-specific scores (0-100 scale)
    # How much F1 knowledge does the submission demonstrate?
    knowledge = Column(Float)

    # How enthusiastic is the fan about F1?
    enthusiasm = Column(Float)

    # How humorous/entertaining is the submission?
    humor = Column(Float)

    # AI-generated brief summary of the submission
    brief_description = Column(Text)

    # Token accounting - tracks AI API usage for cost monitoring
    total_tokens = Column(Float)           # Total tokens used (prompt + completion)
    prompt_tokens = Column(Float)          # Tokens in the input prompt
    completion_tokens = Column(Float)      # Tokens in the AI response
    successful_requests = Column(Float)    # Number of successful API calls
    total_cost = Column(Float)             # Estimated cost in dollars

    # Performance metrics
    time_taken_in_seconds = Column(Float)  # Time for individual AI calls
    total_processing_time_in_seconds = Column(Float)  # Total time for entire evaluation

    # Timestamp when this evaluation was completed
    evaluated_at = Column(DateTime(timezone=True), nullable=False)

    # Relationship: This evaluation belongs to one submission
    submission = relationship("Submission", back_populates="evaluations")


# ---------------------------
# EvalDatabase Class
# ---------------------------
class EvalDatabase:
    """
    Main database interface for F1 Fan Evaluation System.

    This class handles all database operations:
    - Creating/connecting to database
    - Inserting submissions and evaluations
    - Querying data
    - Converting data to pandas DataFrames for analysis
    """

    def __init__(self, db_url: str = None, use_sqlite: bool = True):
        """
        Initialize the database connection.

        Args:
            db_url: Database connection string (e.g., "sqlite:///file.db" or "postgresql://...")
            use_sqlite: If True and db_url is None, uses local SQLite file

        By default, creates a SQLite database file called "f1_fans_eval.db" in the current directory.
        """
        self.logger = logging.getLogger("EvalDatabase")

        # Default to SQLite if no URL provided
        if db_url is None:
            db_url = "sqlite:///f1_fans_eval.db"

        # Create database engine (handles connection pooling)
        self.engine = create_engine(db_url, echo=False)

        # Create session factory (sessions are used for database transactions)
        self.SessionLocal = sessionmaker(bind=self.engine)

        # Make sure tables exist
        self._ensure_initialized()

    @event.listens_for(Engine, "connect")
    def set_sqlite_pragma(dbapi_connection, connection_record):
        """
        SQLite-specific configuration: Enable foreign key constraints.

        By default, SQLite doesn't enforce foreign keys. This ensures that
        if we delete a submission, its evaluations are also deleted (CASCADE).
        """
        if dbapi_connection.__class__.__module__.startswith("sqlite3"):
            cursor = dbapi_connection.cursor()
            cursor.execute("PRAGMA foreign_keys=ON;")
            cursor.close()

    def _ensure_initialized(self):
        """
        Create database tables if they don't exist yet.

        This checks for 'submissions' and 'evaluations' tables, and creates them
        if missing. Safe to run multiple times - won't recreate existing tables.
        """
        Base.metadata.bind = self.engine
        inspector = inspect(self.engine)
        existing_tables = inspector.get_table_names()
        required = {"submissions", "evaluations"}

        if not required.issubset(existing_tables):
            # Create missing tables
            Base.metadata.create_all(self.engine)
            self.logger.info("✅ Database initialized successfully.")
        else:
            self.logger.info("✅ Database already initialized.")

    # ---------------------------
    # Core Operations
    # ---------------------------
    def insert_submission(
        self,
        sub_id: str,
        email: str,
        description: str,
        processed_at=None,
        total_processing_time_in_seconds: float = 0.0,
    ) -> bool:
        """
        Insert or update a submission in the database.

        Args:
            sub_id: Unique submission identifier
            email: User's email address
            description: The text explaining why they're an F1 fan
            processed_at: Timestamp (defaults to now if not provided)
            total_processing_time_in_seconds: How long processing took

        Returns:
            True if successful, False otherwise

        Note: Uses merge() which means if the submission already exists (same sub_id),
        it will be updated with new values instead of throwing an error.
        """
        processed_at = processed_at or datetime.now(timezone.utc)
        with self.SessionLocal() as session:
            try:
                sub = Submission(
                    sub_id=sub_id,
                    email=email,
                    description=description,
                    processed_at=processed_at,
                    total_processing_time_in_seconds=total_processing_time_in_seconds,
                )
                # merge() = insert if new, update if exists
                session.merge(sub)
                session.commit()
                # self.logger.info(f"✅ Inserted submission: {sub_id}")
                return True
            except Exception as e:
                self.logger.error(
                    f"❌ Failed to insert submission {sub_id}: {e}", exc_info=True
                )
                return False

    def insert_evaluation(
        self, eval_id: str, sub_id: str, eval_data: Dict[str, Any]
    ) -> bool:
        """
        Insert or update an evaluation in the database.

        Args:
            eval_id: Unique evaluation identifier
            sub_id: The submission this evaluation is for
            eval_data: Dictionary containing scores, token counts, timestamps, etc.

        Returns:
            True if successful, False otherwise

        The eval_data dictionary should contain keys like:
            - knowledge, enthusiasm, humor (scores)
            - total_tokens, prompt_tokens, etc. (token accounting)
            - evaluated_at (timestamp)
        """
        with self.SessionLocal() as session:
            try:
                # **eval_data unpacks the dictionary as keyword arguments
                eval_entry = Evaluation(eval_id=eval_id, sub_id=sub_id, **eval_data)
                session.merge(eval_entry)
                session.commit()
                self.logger.info(f"✅ Inserted evaluation: {eval_id}")
                return True
            except Exception as e:
                self.logger.error(
                    f"❌ Failed to insert evaluation {eval_id}: {e}", exc_info=True
                )
                return False

    def submission_exists(self, sub_id: str) -> bool:
        """
        Check if a submission already exists in the database.

        Args:
            sub_id: The submission ID to check

        Returns:
            True if submission exists, False otherwise

        Useful for avoiding duplicate processing of the same submission.
        """
        with self.SessionLocal() as session:
            return (
                session.query(Submission).filter_by(sub_id=sub_id).first() is not None
            )

    def evaluation_exists(self, sub_id: str) -> bool:
        """
        Check if an evaluation exists for a given submission.

        Args:
            sub_id: The submission ID to check

        Returns:
            True if at least one evaluation exists for this submission, False otherwise

        Used to avoid re-evaluating submissions that already have scores
        (unless override mode is enabled).
        """
        session = self.SessionLocal()
        try:
            query = session.query(Evaluation).filter(Evaluation.sub_id == sub_id)
            return query.first() is not None
        finally:
            session.close()

    def get_all_submissions(self) -> List[Submission]:
        """
        Retrieve all submissions from the database.

        Returns:
            List of Submission objects

        Useful for batch processing or exporting all data.
        """
        try:
            with self.SessionLocal() as session:
                return session.query(Submission).all()
        finally:
            session.close()

    def get_all_evaluations(self) -> List[Evaluation]:
        """
        Retrieve all evaluations from the database.

        Returns:
            List of Evaluation objects

        Useful for analysis, reporting, or exporting scores.
        """
        try:
            with self.SessionLocal() as session:
                return session.query(Evaluation).all()
        finally:
            session.close()

    def get_all_evaluations_as_df(self) -> pd.DataFrame:
        """
        Get all evaluations as a pandas DataFrame.

        Returns:
            DataFrame with columns: eval_id, sub_id, knowledge, enthusiasm, humor,
            brief_description, token metrics, timestamps, etc.

        This is convenient for data analysis, visualization, and exporting to CSV.
        Each row represents one evaluation.
        """
        rows = self.get_all_evaluations()
        # Convert each evaluation object to a dictionary
        data = [
            {col.name: getattr(row, col.name) for col in Evaluation.__table__.columns}
            for row in rows
        ]
        return pd.DataFrame(data)

    def get_all_submissions_as_df(self) -> pd.DataFrame:
        """
        Get all submissions as a pandas DataFrame.

        Returns:
            DataFrame with columns: id, sub_id, email, description, processed_at,
            total_processing_time_in_seconds

        This is convenient for data analysis, visualization, and exporting to CSV.
        Each row represents one submission.
        """
        rows = self.get_all_submissions()
        # Convert each submission object to a dictionary
        data = [
            {col.name: getattr(row, col.name) for col in Submission.__table__.columns}
            for row in rows
        ]
        return pd.DataFrame(data)

    def delete_all(self):
        """
        Clear all data from the database (DANGEROUS!).

        Deletes ALL evaluations and ALL submissions.
        Use with caution - this cannot be undone!

        Useful for:
        - Resetting the database during development/testing
        - Starting fresh with a new dataset
        """
        with self.SessionLocal() as session:
            # Delete evaluations first (they reference submissions)
            session.query(Evaluation).delete()
            session.query(Submission).delete()
            session.commit()
            self.logger.info("🗑️ All records deleted.")

    def close(self):
        """
        Close the database connection and clean up resources.

        Call this when you're done using the database, especially in long-running
        processes or scripts. This releases connection pool resources.
        """
        self.engine.dispose()


